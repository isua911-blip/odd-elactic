    ax.set_xlabel(r"lattice spacing ratio $a_{\rm lat}/L$")
    ax.set_ylabel(r"relative partition span")
    ax.legend(frameon=False)
    ax.grid(alpha=0.25, which="both")
    _panel_label(ax, "(a)")

