def make_fig1(out: Path) -> None:
    cycle = pd.read_csv(DATA / "baseline_results" / "cycle_scan_ko.csv")

    strip = PassiveCrackedStrip(nx=64, ny=48, crack_half_length=8.0, k=1.0)
    result = strip.solve_initiation(delta_c=0.02)
    u_unit, _, _ = strip.solve(delta=1.0)
    deformed = strip.positions + 8.0 * result.initiation_displacement * u_unit

    fig, axs = plt.subplots(1, 2, figsize=(14.2, 5.2), gridspec_kw={"width_ratios": [1.05, 1.0]})
    ax = axs[0]
    for bid, bond in enumerate(strip.all_bonds):
        if bid in strip.removed_ids:
            continue
        p = deformed[bond.i]
        q = deformed[bond.j].copy()
        dx = q[0] - p[0]
        if dx > strip.period / 2:
            q[0] -= strip.period
        elif dx < -strip.period / 2:
            q[0] += strip.period
        if p[0] < -1 or p[0] > strip.period + 1 or q[0] < -1 or q[0] > strip.period + 1:
            continue
        ax.plot([p[0], q[0]], [p[1], q[1]], linewidth=0.34, alpha=0.52)
    for bid in strip.candidate_ids:
        bond = strip.all_bonds[bid]
        p = deformed[bond.i]
        q = deformed[bond.j].copy()
        dx = q[0] - p[0]
        if dx > strip.period / 2:
            q[0] -= strip.period
        elif dx < -strip.period / 2:
            q[0] += strip.period
        ax.plot([p[0], q[0]], [p[1], q[1]], linewidth=2.0)
    ax.set_aspect("equal")
    ax.set_xlim(0, strip.period)
    ax.set_xlabel("x")
    ax.set_ylabel("y (displacements magnified 8x)")
    ax.set_title("Passive pre-cracked triangular strip at initiation")
    # Local reference-configuration inset: the horizontal cleavage plane is
    # crossed by alternating / and \ bonds; horizontal bonds are parallel to it.
    iax = inset_axes(ax, width="38%", height="46%", loc="lower right", borderpad=1.0)
    right_id = max(strip.candidate_ids, key=lambda bid: strip.all_bonds[bid].midpoint_x or -1e9)
    tipx = float(strip.all_bonds[right_id].midpoint_x)
    tipy = float(0.5*(strip.positions[strip.all_bonds[right_id].i,1]+strip.positions[strip.all_bonds[right_id].j,1]))
    for bid, bond in enumerate(strip.all_bonds):
        p0 = strip.positions[bond.i].copy(); q0 = strip.positions[bond.j].copy()
        dx = q0[0]-p0[0]
        if dx > strip.period/2: q0[0] -= strip.period
        elif dx < -strip.period/2: q0[0] += strip.period
        mid = 0.5*(p0+q0)
        while mid[0]-tipx > strip.period/2: p0[0]-=strip.period; q0[0]-=strip.period; mid[0]-=strip.period
        while mid[0]-tipx < -strip.period/2: p0[0]+=strip.period; q0[0]+=strip.period; mid[0]+=strip.period
        if abs(mid[0]-tipx)>2.4 or abs(mid[1]-tipy)>1.8: continue
        if bid in strip.removed_ids:
            iax.plot([p0[0],q0[0]],[p0[1],q0[1]],'--',lw=1.4)
        elif bid in strip.candidate_ids:
            iax.plot([p0[0],q0[0]],[p0[1],q0[1]],lw=2.4)
        else:
            iax.plot([p0[0],q0[0]],[p0[1],q0[1]],lw=.7,alpha=.65)
    iax.axhline(tipy,ls=':',lw=.9)
    iax.text(tipx-1.35,tipy+.55,r'$\backslash$',fontsize=11)
    iax.text(tipx-.55,tipy+.55,'/',fontsize=11)
    iax.set_xlim(tipx-2.1,tipx+1.8); iax.set_ylim(tipy-1.45,tipy+1.45)
    iax.set_xticks([]); iax.set_yticks([]); iax.set_title("alternating crossing bonds",fontsize=8)
    _panel_label(ax, "(a)", x=-0.20, y=1.04)

    ax = axs[1]
    ax.plot(cycle["k_o"], cycle["work_total_density"], "o", label="finite bond sum")
    order = np.argsort(cycle["k_o"].to_numpy())
    ax.plot(cycle["k_o"].to_numpy()[order], cycle["analytic_density"].to_numpy()[order], "--", label="analytic")
    ax.set_xlabel(r"odd bond coefficient $k_o$")
    ax.set_ylabel(r"cycle work density $W_{\rm loop}/A$")
    ax.legend()
    ax.grid(alpha=0.25)
    _panel_label(ax, "(b)", x=-0.20, y=1.04)

    fig.tight_layout()
    fig.savefig(out / "fig01_model_cycle.pdf", bbox_inches="tight")
    plt.close(fig)


def make_fig2(out: Path) -> None:
    rad = pd.read_csv(DATA / "discrete_configurational_results" / "discrete_domain_radius_scan.csv")
    bal = pd.read_csv(DATA / "discrete_configurational_results" / "discrete_configurational_balance.csv")

    fig, axs = plt.subplots(1, 2, figsize=(9.8, 4.2))
    ax = axs[0]
    for ko in (0.0, 0.05, 0.10, 0.15, 0.20):
        d = rad[np.isclose(rad["k_o"], ko)].sort_values("R")
        ax.plot(d["R"], d["J_total"], "o-", label=fr"$k_o={ko:.2f}$")
    ax.set_xlabel(r"domain radius $R$")
    ax.set_ylabel(r"$J_h[q_R]$")
    ax.legend(fontsize=7.5)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(a)")

    ax = axs[1]
    odd = bal["direct_odd_term"].to_numpy()
    total = bal["excess_total"].to_numpy()
    full = odd + bal["active_change_even"].to_numpy()
    ax.plot(odd, total, "o", label="odd bond term")
    ax.plot(full, total, "s", label="odd + even redistribution")
    lim = 1.08 * max(np.max(np.abs(total)), np.max(np.abs(full)), np.max(np.abs(odd)))
    xx = np.linspace(-lim, lim, 200)
    ax.plot(xx, xx, "--", label="unit slope")
    ax.set_xlabel("discrete source contribution")
    ax.set_ylabel("active excess drift")
    ax.legend(fontsize=7.5)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(b)")

    fig.tight_layout()
    fig.savefig(out / "fig02_configurational_balance.pdf", bbox_inches="tight")
    plt.close(fig)

def make_fig3(out: Path) -> None:
    o = DATA / "protocol_family_results"
    u = pd.read_csv(o / "protocol_family_unit_scan.csv")
    t = pd.read_csv(o / "protocol_family_thresholds.csv")
    p = pd.read_csv(o / "representative_protocol_work_partition.csv")
    m = pd.read_csv(o / "same_endpoint_mobility_protocol_normalized.csv")
    state = pd.read_csv(DATA / "representation_symmetry_results" / "constructive_state_function_criterion.csv")

    fig, axs = plt.subplots(2, 2, figsize=(11.2, 8.0))
    ax = axs[0, 0]
    d = u[u.nx == 48].sort_values("k_o")
    load = 0.9
    s = d.fixed_remote_stress_unit.to_numpy()
    e = d.candidate_extension_unit.to_numpy()
    ad = d.fixed_protocol_work_unit.to_numpy()
    at = d.traction_protocol_work_unit.to_numpy()
    x = d.k_o.to_numpy()
    ax.plot(x, load**2 * s[0] ** 2 * ad / (s**2 * ad[0]), "o-", label="operational, fixed grip")
    ax.plot(x, load**2 * s[0] ** 2 * at / (s**2 * at[0]), "s-", label="operational, matched traction")
    ax.plot(state.k_o, state.state_function_measure, "D--", label=r"state part $-\Delta U_e$")
    ax.plot(x, load * s[0] * e / (s * e[0]), "^-", label="local tensile criterion")
    ax.axhline(1, ls="--", lw=1)
    ax.set_xlabel(r"$k_o/k$")
    ax.set_ylabel("normalized initiation measure")
    ax.legend(frameon=False, fontsize=7.3)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(a)")

    ax = axs[0, 1]
    for nx, mk in [(48, "o"), (64, "s")]:
        d = t[t.nx == nx].sort_values("load_fraction")
        ax.plot(d.load_fraction, d.fixed_grip_work_ratio_at_bond_threshold, mk + "-", label=f"fixed, Nx={nx}")
        ax.plot(d.load_fraction, d.matched_traction_work_ratio_at_bond_threshold, mk + "--", label=f"traction, Nx={nx}")
    ax.axhline(1, ls=":", lw=1)
    ax.set_xlabel(r"$P/P_{\rm init}^{\rm lat}$")
    ax.set_ylabel(r"$A^{\mathcal{P}}/G_c^{\mathcal{P}}$ at bond threshold")
    ax.legend(frameon=False, fontsize=7, ncol=2)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(b)", y=0.88)

    ax = axs[1, 0]
    labels = ["external", "odd", r"$-\Delta U_e$", "diss.", "cut", r"$A^{\mathcal{P}}$"]
    keys = ["external_work", "odd_work", "minus_even_energy_change", "viscous_dissipation", "cut_energy", "protocol_work"]
    xx = np.arange(len(labels))
    w = 0.36
    for name, off in [("fixed grip", -w / 2), ("matched traction", w / 2)]:
        r = p[p.protocol == name.replace(" ", "_")].iloc[0]
        ax.bar(xx + off, [r[k] for k in keys], w, label=name)
    ax.axhline(0, lw=0.8)
    ax.set_xticks(xx, labels, rotation=20)
    ax.set_ylabel("work per virtual advance")
    ax.legend(frameon=False, fontsize=8)
    ax.grid(axis="y", alpha=0.25)
    _panel_label(ax, "(c)")

    ax = axs[1, 1]
    for ko, mk, label in [(0.0, "o", "passive"), (0.12, "s", r"$k_o=0.12$"), (0.222271, "^", r"$k_o=0.222$")]:
        d = m[np.isclose(m.k_o, ko)].sort_values("mobility_ratio")
        ax.plot(d.mobility_ratio, d.protocol_work_over_isotropic, mk + "-", label=label)
    ax.set_xscale("log", base=2)
    ax.set_xticks([0.5, 1, 2, 4], ["0.5", "1", "2", "4"])
    ax.axhline(1, ls=":", lw=1)
    ax.set_xlabel(r"mobility ratio $M_x/M_y$")
    ax.set_ylabel(r"$A^{\mathcal{P}_M}/A^{\mathcal{P}_{M=I}}$")
    ax.legend(frameon=False, fontsize=8)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(d)", y=0.88)

    fig.tight_layout()
    fig.savefig(out / "fig04_protocol_family.pdf")
    plt.close(fig)


