def make_fig7(out: Path) -> None:
    summary = pd.read_csv(DATA / "directional_driving_results" / "directional_case_summary.csv")
    work = pd.read_csv(DATA / "directional_driving_results" / "directional_protocol_work.csv")
    force = pd.read_csv(DATA / "directional_driving_results" / "directional_configurational_force.csv")

    fig, axs = plt.subplots(2, 2, figsize=(11.0, 8.2))

    ax = axs[0, 0]
    for angle, marker in [(-60, "o"), (0, "s"), (60, "^")]:
        radians = np.deg2rad(angle)
        endpoint = np.array([np.cos(radians), np.sin(radians)])
        ax.annotate("", xy=endpoint, xytext=(0, 0), arrowprops=dict(arrowstyle="->", linewidth=1.8))
        ax.plot(endpoint[0], endpoint[1], marker)
        ax.text(1.08 * endpoint[0], 1.08 * endpoint[1], fr"${angle}^\circ$", ha="center", va="center")
    ax.plot(0, 0, "ko", markersize=4)
    ax.set_aspect("equal")
    ax.set_xlim(-0.05, 1.2)
    ax.set_ylim(-1.05, 1.05)
    ax.set_xlabel(r"local crack-advance direction $X_1$")
    ax.set_ylabel(r"$X_2$")
    ax.set_title("Equal-length two-edge dual paths")
    ax.grid(alpha=0.25)
    _panel_label(ax, "(a)")

    ax = axs[0, 1]
    d = work[(work.nx == 48) & (work.tip == "right")].copy()
    passive_straight = float(d[(np.isclose(d.k_o, 0.0)) & (d.direction_deg == 0)].protocol_work_unit.iloc[0])
    for ko, marker in [(-0.2, "o-"), (0.0, "s--"), (0.2, "^-")]:
        q = d[np.isclose(d.k_o, ko)].sort_values("direction_deg")
        ax.plot(q.direction_deg, q.protocol_work_unit / passive_straight, marker, label=fr"$k_o/k={ko:+.1f}$")
    ax.set_xticks([-60, 0, 60], [r"$-60^\circ$", r"$0^\circ$", r"$+60^\circ$"])
    ax.set_xlabel("virtual extension direction")
    ax.set_ylabel(r"$A^{\mathcal{P}}(\varphi)/A_0^{\mathcal{P}}(0)$")
    ax.set_title(r"$48\times36$ right tip")
    ax.legend(frameon=False, fontsize=8)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(b)")

    ax = axs[1, 0]
    for ko, marker in [(-0.2, "o-"), (0.2, "s-")]:
        q = summary[(summary.tip == "right") & np.isclose(summary.k_o, ko)].sort_values("a_lat_over_L")
        ax.plot(q.a_lat_over_L, q.odd_excess_kink_work_bias_over_passive_straight, marker, label=fr"$k_o/k={ko:+.1f}$")
    ax.axhline(0.0, linestyle=":", linewidth=1.0)
    ax.set_xlabel(r"lattice spacing ratio $a_{\rm lat}/L$")
    ax.set_ylabel(r"$\{[A_+-A_-]_{k_o}-[A_+-A_-]_0\}/A_0(0)$")
    ax.set_title("Odd-induced directional excess")
    ax.legend(frameon=False, fontsize=8)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(c)")

    ax = axs[1, 1]
    q = force[(force.nx == 48) & (force.tip == "right") & np.isclose(force.R_over_L, 0.10)]
    passive_x = float(q[(np.isclose(q.k_o, 0.0)) & (q.direction_deg == 0) & np.isclose(q.alpha_upper, 0.5)].J_total_x.iloc[0])
    for ko, marker in [(-0.2, "o-"), (0.2, "s-")]:
        vals = []
        alphas = []
        for alpha in sorted(q.alpha_upper.unique()):
            z = q[np.isclose(q.k_o, ko) & np.isclose(q.alpha_upper, alpha)]
            plus = float(z[z.direction_deg == 60].odd_excess_J_projection.iloc[0])
            minus = float(z[z.direction_deg == -60].odd_excess_J_projection.iloc[0])
            alphas.append(alpha)
            vals.append((plus - minus) / passive_x)
        ax.plot(alphas, vals, marker, label=fr"$k_o/k={ko:+.1f}$")
    ax.axhline(0.0, linestyle=":", linewidth=1.0)
    ax.set_xlabel(r"upper-triangle localization share $\alpha$")
    ax.set_ylabel(r"odd-excess $[J(+60^\circ)-J(-60^\circ)]/J_x^0$")
    ax.set_title(r"Configurational sign is partition-robust, $R/L=0.10$")
    ax.legend(frameon=False, fontsize=8)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(d)")

    fig.tight_layout()
    fig.savefig(out / "fig07_directional_driving.pdf", bbox_inches="tight")
    plt.close(fig)

