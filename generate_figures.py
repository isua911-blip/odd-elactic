def make_fig6_propagation(out: Path) -> None:
    steps = pd.read_csv(DATA / "advance_resistance_results" / "advance_scaled_steps.csv")
    periods = pd.read_csv(DATA / "advance_resistance_results" / "advance_period_summary.csv")
    cascades = pd.read_csv(DATA / "advance_resistance_results" / "cascade_robustness_scan.csv")
    positive = pd.read_csv(DATA / "advance_resistance_results" / "positive_control_scan.csv")

    nominal = steps[
        (steps.nx == 48)
        & np.isclose(steps.crack_fraction, 0.125)
        & np.isclose(steps.load_fraction, 0.90)
        & np.isclose(steps.k_o, 0.20)
    ].sort_values(["boundary_condition", "step"])
    comparison = pd.read_csv(DATA / "refinement_validation_results" / "passive_active_step_comparison.csv")

    fig, axs = plt.subplots(2, 2, figsize=(11.0, 8.2))
    ax = axs[0, 0]
    passive = comparison[np.isclose(comparison.k_o, 0.0)].sort_values("step")
    active = comparison[np.isclose(comparison.k_o, 0.2)].sort_values("step")
    ax.plot(passive.step, passive.extension_ratio, "o--", label=r"passive $\delta\ell_n/\delta_c$")
    ax.plot(active.step, active.extension_ratio, "s-", label=r"active $\delta\ell_n/\delta_c$")
    ax.plot(active.step, active.work_ratio, "^-", label=r"active $A_n^{\mathcal{P}}/R_n^{\rm eff}$")
    ax.axhline(1.0, linestyle=":", linewidth=1.0)
    ax.set_xticks([1, 2, 3, 4])
    ax.set_xlabel("successive crack-plane bond $n$")
    ax.set_ylabel("normalized step measure")
    ax.set_title(r"Fixed grip: $P/P_{\rm init}=0.90$")
    ax.legend(frameon=False, fontsize=8)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(a)")

    ax = axs[0, 1]
    for bc, marker, label in [
        ("fixed_grip", "o-", "fixed grip"),
        ("dead_load", "s--", "constant traction"),
    ]:
        d = nominal[nominal.boundary_condition == bc]
        ax.plot(d.step, d.odd_work / d.effective_resistance, marker, label=label)
    ax.axhline(0.0, linestyle=":", linewidth=1.0)
    ax.set_xticks([1, 2, 3, 4])
    ax.set_xlabel("successive crack-plane bond $n$")
    ax.set_ylabel(r"$W_{\mathrm{odd},n}/R_n^{\mathrm{eff}}$")
    ax.set_title("Odd work alternates over two lattice periods")
    ax.legend(frameon=False, fontsize=8)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(b)")

    ax = axs[1, 0]
    d = periods[
        np.isclose(periods.crack_fraction, 0.125)
        & np.isclose(periods.load_fraction, 0.90)
        & np.isclose(periods.k_o, 0.20)
    ].copy()
    d["a_over_L"] = 1.0 / d.nx
    for bc, period, marker, label in [
        ("fixed_grip", 1, "o-", "fixed, period 1"),
        ("fixed_grip", 2, "s-", "fixed, period 2"),
        ("dead_load", 1, "o--", "traction, period 1"),
        ("dead_load", 2, "s--", "traction, period 2"),
    ]:
        q = d[(d.boundary_condition == bc) & (d.period == period)].sort_values("a_over_L")
        ax.plot(q.a_over_L, q.work_ratio, marker, label=label)
    ax.axhline(1.0, linestyle=":", linewidth=1.0)
    ax.axvline(1.0 / 32.0, linestyle=":", linewidth=0.8)
    ax.text(1.0 / 32.0, ax.get_ylim()[0] + 0.02 * (ax.get_ylim()[1] - ax.get_ylim()[0]),
            r"$a_0=4a_{\rm lat}$", rotation=90, va="bottom", ha="right", fontsize=7)
    ax.set_xlabel(r"lattice spacing ratio $a_{\rm lat}/L$")
    ax.set_ylabel(r"$(A_{2m-1}+A_{2m})/(R_{2m-1}+R_{2m})$")
    ax.set_title(r"Cleavage-period balance at $P/P_{\mathrm{init}}=0.90$")
    ax.legend(frameon=False, fontsize=7, ncol=2)
    ax.grid(alpha=0.25)
    _panel_label(ax, "(c)")

    ax = axs[1, 1]
    unrestricted = pd.read_csv(DATA / "configurational_work_bridge_results" / "unrestricted_all_bond_cascades.csv")
    p_values = sorted(unrestricted.load_fraction.unique())
    base = unrestricted[(unrestricted.nx == 48) & np.isclose(unrestricted.crack_fraction, 0.125)
                        & (unrestricted.boundary_condition == "dead_load")]
    for ko, marker in [(0.0, "o-"), (0.12, "s--"), (0.20, "^-."), (0.30, "d:")]:
        d = base[np.isclose(base.k_o, ko)]
        if d.empty:
            continue
        ax.plot(p_values,
                [int(d[np.isclose(d.load_fraction, p)].broken_bonds.iloc[0]) for p in p_values],
                marker, label=fr"$k_o/k={ko:g}$")
    cutoff = int(unrestricted.broken_bonds.max())
    ax.axhline(cutoff, ls=":", lw=1, color="0.4")
    ax.set_xlabel(r"initial load $P/P_{\mathrm{init}}$")
    ax.set_ylabel("all-bond deletions")
    ax.set_title("Activity lowers the cascade threshold")
    ax.text(0.03, 0.94,
            f"$48\\times36$, $a_0/L=0.125$, constant traction\n92/224 states reach the {cutoff}-deletion cutoff",
            transform=ax.transAxes, va="top", fontsize=7,
            bbox={"boxstyle": "round,pad=0.25", "facecolor": "white", "alpha": 0.8, "linewidth": 0.6})
    ax.legend(frameon=False, fontsize=7.5, loc="center right")
    ax.grid(alpha=.25)
    _panel_label(ax, "(d)")

    fig.tight_layout()
    fig.savefig(out / "fig06_propagation_and_branching.pdf", bbox_inches="tight")
    plt.close(fig)

